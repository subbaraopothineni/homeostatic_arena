"""Write results/v02/report.md from the result tables (no numbers typed by hand)."""
from __future__ import annotations

import math
from pathlib import Path

import numpy as np

from experiments.plots_v02 import CONDS, HYP_TITLES

HYPS = list(HYP_TITLES)


def _f(x) -> float:
    try:
        return float(x)
    except (TypeError, ValueError):
        return math.nan


def _ci(r: dict, digits: int = 3) -> str:
    m, lo, hi = _f(r["mean"]), _f(r["ci_low"]), _f(r["ci_high"])
    if math.isnan(m):
        return "n/a"
    return f"{m:.{digits}f} [{lo:.{digits}f}, {hi:.{digits}f}]"


def _true(x) -> bool:
    return str(x) == "True"


def _table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


PREREG = {"agency": ("Study 2", "docs/preregistration_v0.2.md"),
          "agency_b": ("Study 2b", "docs/preregistration_v0.2b.md (Part A; tests and rules from "
                                   "docs/preregistration_v0.2.md)")}
ECOLOGICAL_EPISODES = 50


def write(tables: dict[str, list[dict]], verdicts: dict, spont_step: int, out: Path,
          world: str = "agency") -> None:
    hyp, relpe, runs = tables["hypotheses"], tables["relpe"], tables["runs"]
    study, prereg = PREREG.get(world, (world, "docs/"))
    lines = [f"# {study} results: functional self/world and self/other tests", "",
             f"Generated by `python -m experiments.run_v02` (world `{world}`). Hypotheses, "
             f"controls and pass rules: `{prereg}`. These are functional measurements; no "
             "claim about subjective experience is made.", ""]

    # ---------------------------------------------------------------- verdicts
    lines += ["## Verdicts (pass rule: CI excludes 0 in ≥ 4 of 5 runs)", ""]
    rows = []
    for h in HYPS:
        f, u = verdicts[f"FULL:{h}"], verdicts[f"UNTRAINED:{h}"]
        na = f" ({f['not_applicable']} n/a)" if f["not_applicable"] else ""
        rows.append([h.split("_")[0], f"{f['passing_runs']}/{f['runs']}{na}", f["verdict"],
                     f"{u['passing_runs']}/{u['runs']}", u["verdict"]])
    lines += [_table(["Hypothesis", "FULL runs passing", "FULL verdict",
                      "UNTRAINED runs passing", "UNTRAINED verdict"], rows), ""]
    v1, v2 = verdicts["V1_untrained_not_fooled"], verdicts["V2_comparator_passes_H1_H2"]
    lines += [f"- **V1** (UNTRAINED must not pass H1–H3a): "
              f"{'OK' if v1['ok'] else 'FAILED, fooled on ' + ', '.join(v1['fooled_by_untrained'])}",
              f"- **V2** (COMPARATOR must pass H1 and H2): {'OK' if v2['ok'] else 'FAILED'}",
              "- **V3** (position-rule self-attribution accuracy): " + ", ".join(
                  f"{k.split(':')[1]} {v:.2f}" for k, v in verdicts["V3_position_rule_accuracy"].items()),
              ""]

    # ---------------------------------------------------------------- gate
    lines += ["## Competence gate and survival (20 held-out free-running episodes)", ""]
    rows = [[r["label"], f"{_f(r.get('fwd_over_nochange')):.3f}", r.get("gate_passed", ""),
             f"{_f(r.get('survived_frac')):.2f}", f"{_f(r.get('survival_s')):.1f}"]
            for r in runs if r["variant"] in ("FULL", "NOEFF", "NOFWD") and not _true(r.get("missing"))]
    lines += [_table(["Run", "prediction error / no-change", "gate (≤ 0.8)",
                      "survived 60 s", "mean survival (s)"], rows), "",
              "The gate applies to FULL and NOEFF; NOFWD has no trained forward model. Note the "
              "gate uses all 26 channels, some of which (efference copy) are trivially "
              "predictable given the action.", ""]
    if world == "agency_b":
        eco = tables["ecological"]
        rows = []
        for lab in sorted({r["label"] for r in runs if r["variant"] == "FULL"}):
            n_self = sum(r["cause"] == "self" for r in eco if r["label"] == lab)
            rate = n_self / ECOLOGICAL_EPISODES
            rows.append([lab, f"{rate:.2f}", "yes" if rate >= 1.0 else "no"])
        n_ok = sum(r[2] == "yes" for r in rows)
        lines += ["## Manipulation check M1 (pre-registered for Study 2b)", "",
                  _table(["Run", "self-caused lamp toggles per free-running episode",
                          "meets >= 1.0"], rows), "",
                  f"**M1: {n_ok}/{len(rows)} runs meet it → manipulation "
                  f"{'succeeded' if n_ok >= 4 else 'FAILED'}.** (H1–H3 are evaluated as "
                  "registered either way.)", ""]
    missing = [r["label"] for r in runs if _true(r.get("missing"))]
    if missing:
        lines += [f"**Missing models:** {', '.join(missing)} (count as not supporting).", ""]

    # ---------------------------------------------------------------- effects per run
    lines += ["## Effects per run (mean [95% CI])", ""]
    labels = list(dict.fromkeys(r["label"] for r in hyp if r["label"] != "NO-CHANGE"))
    rows = []
    for lab in labels:
        row = [lab]
        for h in HYPS:
            r = next((x for x in hyp if x["label"] == lab and x["effect"] == h), None)
            mark = {"True": " ✓", "None": " (n/a)"}.get(str(r["counts_for_verdict"]), "") if r else ""
            row.append(_ci(r) + mark if r else "")
        rows.append(row)
    lines += [_table(["Run"] + [h.split("_")[0] for h in HYPS], rows), "",
              "✓ = counts toward the verdict (CI excludes 0, gate passed, applicable).", ""]

    # ---------------------------------------------------------------- relPE
    lines += ["## Relative prediction error at the lamp change (mean over runs)", "",
              f"SPONT/NOEVENT events were timed at step {spont_step} (median SELF entry).", ""]
    rows = []
    for g in ("FULL", "NOEFF", "NOFWD", "UNTRAINED", "COMPARATOR", "NO-CHANGE"):
        row = [g]
        for c in CONDS + ("SELF|self-blind", "OTHER|other-blind"):
            vals = [_f(r["mean"]) for r in relpe if r["variant"] == g and r["condition"] == c]
            row.append(f"{np.mean(vals):.3f}" if vals else "")
        rows.append(row)
    lines += [_table(["Predictor"] + list(CONDS) + ["SELF self-blind", "OTHER other-blind"],
                     rows), ""]

    # ---------------------------------------------------------------- secondary
    lines += ["## Secondary analyses", ""]
    s1 = [x for x in hyp if x["effect"] == "S1_other_minus_self" and x["variant"] == "FULL"]
    lines += ["- relPE(OTHER) − relPE(SELF), FULL runs: " + "; ".join(
        f"{x['label']}: {_ci(x)}" for x in s1)]
    for v in ("NOEFF", "NOFWD"):
        h1 = [x for x in hyp if x["effect"] == "H1_spont_minus_self" and x["variant"] == v]
        lines.append(f"- H1 effect in {v}: " + "; ".join(f"{x['label']}: {_ci(x)}" for x in h1))
    eco = tables["ecological"]
    if eco:
        by = {}
        for r in eco:
            by.setdefault(r["cause"], []).append(_f(r["rel_pe"]))
        lines.append("- Ecological check (natural toggles in free-running FULL episodes), median "
                     "relPE by cause: " + "; ".join(
                         f"{c}: {np.nanmedian(v):.3f} (n={len(v)})" for c, v in sorted(by.items())))
    lines.append("")

    # ---------------------------------------------------------------- T1
    t1 = tables["t1_trials"]
    lines += ["## T1 body vs world (descriptive; pre-registered as expected to be fooled)", ""]
    rows = []
    for g in ("FULL", "UNTRAINED", "NO-CHANGE"):
        row = [g]
        for c in ("WORLD", "BODY", "NONE"):
            vals = [_f(r["intero_share"]) for r in t1 if r["variant"] == g and r["condition"] == c]
            row.append(f"{np.nanmean(vals):.3f}" if vals else "")
        rows.append(row)
    lines += [_table(["Predictor", "WORLD", "BODY", "NONE"], rows),
              "", "Share of prediction error on body channels (energy, damage) at the event.", ""]
    beh = tables["t1_behaviour"]
    rows = []
    for g in ("FULL", "REFLEX"):
        row = [g]
        for c in ("WORLD", "BODY", "NONE"):
            vals = [_f(r["toward_charger_m"]) for r in beh if r["variant"] == g and r["condition"] == c]
            row.append(f"{np.mean(vals):+.2f}" if vals else "")
        rows.append(row)
    lines += [_table(["Agent", "WORLD", "BODY", "NONE"], rows), "",
              "Movement toward the charger in the 5 s after the event (m).", ""]

    # ---------------------------------------------------------------- probes
    probes = tables["probes"]
    lines += ["## Exploratory probes (cross-validated decoding accuracy; chance = 0.33)", ""]
    keys = sorted({(r["probe"], int(r["lag"])) for r in probes})
    rows = []
    for g in ("FULL", "UNTRAINED", "RAW-INPUT"):
        row = [g]
        for p, lag in keys:
            vals = [_f(r["accuracy"]) for r in probes if r["variant"] == g
                    and r["probe"] == p and int(r["lag"]) == lag]
            row.append(f"{np.mean(vals):.2f}" if vals else "")
        rows.append(row)
    lines += [_table(["Features"] + [f"{p} @ lag {lag}" for p, lag in keys], rows), "",
              "Decoding success is not evidence of self-awareness unless it exceeds the "
              "RAW-INPUT baseline (pre-registered).", ""]

    lines += ["## Figures", ""] + [f"![{n}]({n}.png)" for n in (
        "fig_hypotheses", "fig_relpe", "fig_dissociation", "fig_t1_body_world", "fig_probes",
        "fig_training")]
    (out / "report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
